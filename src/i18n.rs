//! Multilingual interface translations with desktop locale detection.

use std::env;

/// Resolve the configured language. `system` follows the desktop locale.
pub fn language(setting: &str) -> &'static str {
    fn from_locale(value: &str) -> Option<&'static str> {
        let value = value.to_ascii_lowercase();
        let value = value.split(':').next().unwrap_or(&value);
        let value = value.split(|c| c == '_' || c == '-' || c == '.').next().unwrap_or(&value);
        match value {
            "de" => Some("de"),
            "en" => Some("en"),
            "es" => Some("es"),
            "nl" => Some("nl"),
            "fr" => Some("fr"),
            "it" => Some("it"),
            "sv" => Some("sv"),
            "pt" => Some("pt"),
            "pl" => Some("pl"),
            "da" => Some("da"),
            "no" | "nb" | "nn" => Some("no"),
            _ => None,
        }
    }

    if setting != "system" {
        if let Some(language) = from_locale(setting) {
            return language;
        }
    }
    for key in ["LANGUAGE", "LC_ALL", "LC_MESSAGES", "LANG"] {
        if let Ok(value) = env::var(key) {
            if let Some(language) = from_locale(&value) {
                return language;
            }
        }
    }
    "en"
}

